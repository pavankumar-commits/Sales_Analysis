select * from sales_analytics;

--- 1.Write a query to identify rows where Total_Sales_USD does not match Quantity * Unit_Price_USD due to missing data.

SELECT QUANTITY,UNIT_PRICE_USD,TOTAL_SALES_USD,(QUANTITY*UNIT_PRICE_USD) AS CALCULATED_SALES FROM SALES_ANALYTICS
WHERE TOTAL_SALES_USD <> (QUANTITY*UNIT_PRICE_USD);

--- 2.Extract the year and month from Order_Date and calculate total monthly revenue and order counts.

SELECT year(ORDER_DATE) AS YEAR,month(ORDER_DATE) AS MONTH,COUNT(ORDER_ID) AS NO_OF_ORDERS,sum(TOTAL_SALES_USD) AS MONTHLY_REVENUE
FROM SALES_ANALYTICS GROUP BY  year(ORDER_DATE),month(ORDER_DATE) ORDER BY YEAR,MONTH;

--- 3.Calculate total revenue and total quantity sold by Region and Category

SELECT REGION,CATEGORY,sum(TOTAL_SALES_USD) AS TOTAL_REVENUE,sum(QUANTITY) AS TOTAL_QUANTITY FROM SALES_ANALYTICS 
GROUP BY REGION,CATEGORY ORDER BY REGION,TOTAL_REVENUE DESC;

--- 4. find the top 3 best-selling products by total revenue within each product category.

with RANKEDPRODUCTS AS (SELECT CATEGORY,PRODUCT_NAME,sum(TOTAL_SALES_USD) AS TOTAL_REVENUE,DENSE_RANK() 
OVER (PARTITION BY CATEGORY ORDER BY sum(TOTAL_SALES_USD) DESC) as PRODUCT_RANK FROM SALES_ANALYTICS GROUP BY CATEGORY,PRODUCT_NAME)
SELECT CATEGORY,PRODUCT_NAME,TOTAL_REVENUE,PRODUCT_RANK FROM RANKEDPRODUCTS WHERE PRODUCT_RANK <= 3 ORDER BY CATEGORY, PRODUCT_RANK;

--- 5. Identify orders where Total_Sales_USD is greater than 2 times the average order value of their respective region.

   WITH REGIONAVERAGES AS (
    SELECT ORDER_ID,ORDER_DATE,REGION,CATEGORY,PRODUCT_NAME,TOTAL_SALES_USD,AVG(TOTAL_SALES_USD) OVER (PARTITION BY REGION) AS AVG_REGION_SALES 
    FROM SALES_ANALYTICS)SELECT ORDER_ID,REGION,TOTAL_SALES_USD,ROUND(AVG_REGION_SALES, 2) AS AVG_REGION_SALES,
    ROUND(2 * AVG_REGION_SALES, 2) AS DOUBLE_REGIONAL_AVG FROM REGIONAVERAGES WHERE TOTAL_SALES_USD > (2 * AVG_REGION_SALES)
    ORDER BY REGION, TOTAL_SALES_USD DESC;
    
--- 6.Calculate the percentage contribution of each product category to the overall company total revenue.

SELECT CATEGORY,SUM(TOTAL_SALES_USD) AS CATEGORY_REVENUE,SUM(SUM(TOTAL_SALES_USD)) OVER () AS TOTAL_COMPANY_REVENUE,
ROUND((SUM(TOTAL_SALES_USD) * 100.0) / SUM(SUM(TOTAL_SALES_USD)) OVER (), 2) AS PERCENTAGE_CONTRIBUTION FROM SALES_ANALYTICS 
 GROUP BY CATEGORY ORDER BY CATEGORY_REVENUE DESC;

--- 7. Order Frequency by Day/Month: Find which month or date range had the highest volume of unique Order_ID transactions.

SELECT ORDER_DATE,COUNT(DISTINCT ORDER_ID) AS UNIQUE_ORDER_COUNT FROM SALES_ANALYTICS 
 GROUP BY ORDER_DATE ORDER BY UNIQUE_ORDER_COUNT DESC;

--- 8. find null values
SELECT * FROM SALES_ANALYTICS WHERE 
ORDER_ID IS NULL
OR ORDER_DATE IS NULL
OR REGION IS NULL
OR CATEGORY IS NULL
OR PRODUCT_NAME IS NULL
OR QUANTITY IS NULL
OR UNIT_PRICE_USD IS NULL
OR TOTAL_SALES_USD IS NULL;

--- 9.--- empty rows
SELECT * FROM SALES_ANALYTICS WHERE 
TRIM(ORDER_ID) = ''
OR TRIM(ORDER_DATE) = ''
OR TRIM(REGION) = ''
OR TRIM(CATEGORY) = ''
OR TRIM(PRODUCT_NAME) = ''
OR TRIM(QUANTITY) = ''
OR TRIM(UNIT_PRICE_USD) = ''
OR TRIM(TOTAL_SALES_USD) = '';

